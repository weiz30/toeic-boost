# ---------- validation helpers ----------
CATS = [A, F, H, S, P, T]
records = []
seen = {}
for (w, pos, zh, ph, ex, ezh, cat) in DATA:
    key = w.strip().lower()
    assert key not in seen, f"duplicate word: {key}"
    seen[key] = True
    n = len(ex.split())
    assert 10 <= n <= 16, f"example length {n} for {key}: {ex}"
    assert pos in {"n.", "v.", "adj.", "adv.", "phr."}, pos
    assert zh.count("；") <= 2, f"too many senses: {key}"
    records.append({"w": key, "pos": pos, "zh": zh, "ph": ph,
                    "ex": ex, "ezh": ezh, "cat": cat})

counts = collections.Counter(r["cat"] for r in records)
assert len(records) == 150, len(records)
assert all(counts[c] == 25 for c in CATS), counts

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "vocab.json")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    json.dump(records, f, ensure_ascii=False, indent=2)
    f.write("\n")
print("written:", out)
print("total:", len(records))
print("counts:", dict(counts))
